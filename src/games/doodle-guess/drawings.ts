/* Doodle Guess — the drawings. Each is a list of pencil strokes on a 100 ×
   100 page, in the order they're drawn. The order is the puzzle: vague
   details first, the giveaway last. */

export type Stroke =
  | { t: 'l'; p: number[]; close?: boolean } // polyline through x,y pairs
  | { t: 'c'; x: number; y: number; r: number } // circle
  | { t: 'e'; x: number; y: number; rx: number; ry: number } // ellipse
  | { t: 'a'; x: number; y: number; r: number; from: number; to: number } // arc, degrees clockwise from →
  | { t: 'q'; p: [number, number, number, number, number, number] }; // quadratic curve

export type Category = 'animal' | 'food' | 'object' | 'place' | 'nature' | 'vehicle' | 'character';

export interface Drawing {
  id: string;
  answer: string;
  /** Other words that count as right. */
  also: string[];
  category: Category;
  strokes: Stroke[];
}

const L = (...p: number[]): Stroke => ({ t: 'l', p });
const Z = (...p: number[]): Stroke => ({ t: 'l', p, close: true });
const C = (x: number, y: number, r: number): Stroke => ({ t: 'c', x, y, r });
const E = (x: number, y: number, rx: number, ry: number): Stroke => ({ t: 'e', x, y, rx, ry });
const A = (x: number, y: number, r: number, from: number, to: number): Stroke => ({ t: 'a', x, y, r, from, to });
const Q = (x0: number, y0: number, cx: number, cy: number, x1: number, y1: number): Stroke => ({ t: 'q', p: [x0, y0, cx, cy, x1, y1] });

const d = (id: string, category: Category, also: string[], ...strokes: Stroke[]): Drawing =>
  ({ id, answer: id.replace(/-/g, ' '), also, category, strokes });

